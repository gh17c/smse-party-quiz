function shuffledOptions(entries, correctTexts, randomKey) {
  const offset = randomKey % entries.length;
  const rotated = [...entries.slice(offset), ...entries.slice(0, offset)];
  const options = rotated.map((text, index) => ({ id: String.fromCharCode(65 + index), text }));
  const answer = options.filter((option) => correctTexts.includes(option.text)).map((option) => option.id);
  return { options, answer };
}

function buildPackQuestions(pack) {
  const source = sources[pack.source];
  const questions = [];
  pack.items.forEach(([number, basis, factA, factB, mythA, mythB, explanation], index) => {
    const conceptId = `${pack.code}-knowledge-${number}`;
    const common = {
      topic: pack.topic,
      source,
      conceptId,
      annotation: {
        basis,
        pitfall: `易错辨析：${mythA}。正确要求是：${factA}。核对时重点看适用主体、前置条件和程序边界。`,
      },
    };
    const singleSet = shuffledOptions([factA, mythA, mythB, '以上说法均不正确'], [factA], index);
    questions.push({
      ...common,
      id: `${pack.code}x${number}s`,
      type: 'single',
      stem: `关于${basis}，下列哪项表述准确？`,
      options: singleSet.options,
      answer: singleSet.answer[0],
      explanation,
    });
    const multipleSet = shuffledOptions([factA, mythA, factB, mythB], [factA, factB], index + 1);
    questions.push({
      ...common,
      id: `${pack.code}x${number}m`,
      type: 'multiple',
      stem: `依据${basis}，下列哪些表述正确？`,
      options: multipleSet.options,
      answer: multipleSet.answer,
      explanation,
    });
    questions.push({
      ...common,
      id: `${pack.code}x${number}jt`,
      type: 'judge',
      stem: factA + '。',
      options: [],
      answer: true,
      explanation,
    });
    questions.push({
      ...common,
      id: `${pack.code}x${number}jf`,
      type: 'judge',
      stem: mythA + '。',
      options: [],
      answer: false,
      explanation,
    });
  });
  return questions;
}

export const expandedQuestionBank = packs.flatMap(buildPackQuestions);
