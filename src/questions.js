const options = (...texts) => texts.map((text, index) => ({ id: String.fromCharCode(65 + index), text }));
const annotation = (type, choices, answer, explanation, source) => {
  const citation = explanation.match(/(?:党章|条例|细则|规划建议)(第[一二三四五六七八九十百零〇\d]+条(?:第[一二三四五六七八九十百零〇\d]+项)?)/)?.[0];
  const correctIds = Array.isArray(answer) ? answer : [answer];
  const correctTexts = choices.filter((choice) => correctIds.includes(choice.id)).map((choice) => choice.text);
  const distractors = choices.filter((choice) => !correctIds.includes(choice.id)).slice(0, 2).map((choice) => choice.text);
  let pitfall;
  if (type === 'judge') {
    pitfall = `易错辨析：本题结论为“${answer ? '正确' : '错误'}”。判断时应对照题干中的主体、条件和程序，而不是只凭关键词作答。`;
  } else if (type === 'multiple') {
    pitfall = `易错辨析：应选出全部正确项（${correctTexts.join('；')}）。${distractors.length ? `注意排除：${distractors.join('；')}。` : ''}漏选或错选都会影响本题得分。`;
  } else {
    pitfall = `易错辨析：正确表述是“${correctTexts[0]}”。${distractors.length ? `注意与“${distractors.join('；')}”区分。` : ''}核对时留意题目中的适用主体与条件。`;
  }
  return { basis: citation || source.title, pitfall };
};
const single = (id, topic, stem, answer, choices, explanation, source = constitution) => ({
  id, topic, type: 'single', stem, options: options(...choices), answer, explanation, source,
  annotation: annotation('single', options(...choices), answer, explanation, source),
});
const multiple = (id, topic, stem, answer, choices, explanation, source = constitution) => ({
  id, topic, type: 'multiple', stem, options: options(...choices), answer, explanation, source,
  annotation: annotation('multiple', options(...choices), answer, explanation, source),
});
const judge = (id, topic, stem, answer, explanation, source = constitution) => ({
  id, topic, type: 'judge', stem, options: [], answer, explanation, source,
  annotation: annotation('judge', [], answer, explanation, source),
});

